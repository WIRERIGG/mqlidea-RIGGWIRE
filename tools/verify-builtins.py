#!/usr/bin/env python3
"""Writes an MQL5 script calling each given built-in function name bare (Name();), plus one
bogus name. Compile it in MetaEditor: every real name gives "wrong parameters count" or compiles,
never "undeclared identifier"; the bogus one must give "undeclared identifier" (proves the check
bites). This is how names in mql5-builtin-functions.json are confirmed.
Usage: tools/verify-builtins.py OUT.mq5 Name [Name ...]"""
import pathlib, sys

lines = ["// generated by tools/verify-builtins.py", "void OnStart()", "  {"]
lines += [f"   {name}();" for name in sys.argv[2:]]
lines += ["   NotABuiltinXyz();   // the one expected 'undeclared identifier'", "  }"]
pathlib.Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
