#!/usr/bin/env python3
"""Writes an MQL5 script touching every name in mql5-structs.json, plus one bogus member.
Compile it in MetaEditor: the only error must be the bogus one (proves the check bites).
Usage: tools/verify-structs.py OUT.mq5"""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
catalog = json.loads((root / "src/main/resources/mql/doc/mql5-structs.json").read_text())
lines = ["// generated by tools/verify-structs.py", "void OnStart()", "  {"]
for i, (name, members) in enumerate(k for k in catalog.items() if not k[0].startswith("_")):
    lines.append(f"   {name} v{i};")
    lines.extend(f"   Print(v{i}.{f});" for f in members.get("fields", []))
    lines.extend(f"   Print(ArraySize(v{i}.{f}));" for f in members.get("arrays", []))
    lines.extend(f"   Print(v{i}.{m}());" for m in members.get("methods", []))
lines.append("   MqlDateTime bogus; Print(bogus.not_a_member_xyz);   // the one expected error")
lines.append("  }")
pathlib.Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
